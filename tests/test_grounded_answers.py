def test_why_still_investigating_answers_question_before_evidence(
    service: ChatService,
) -> None:
    response = service.chat(
        "Why is CASE-4821 still under investigation?",
        DEMO_USERS["demo-agent-alex"],
    )

    assert "does not confirm a single reason" in response.reply
    assert "currently In Progress" in response.reply
    assert "We are given" not in response.reply
    assert all(
        citation.citation_label in response.reply
        for citation in response.citations
    )


def test_resolution_guarantee_is_refused_without_evidence_dump(
    service: ChatService,
) -> None:
    response = service.chat(
        "Can you guarantee CASE-4821 will be resolved tomorrow?",
        DEMO_USERS["demo-agent-alex"],
    )

    assert "cannot guarantee" in response.reply
    assert "no confirmed resolution date" in response.reply
    assert "three consecutive synchronization windows" not in response.reply
    assert {citation.source_id for citation in response.citations} == {
        "CRM-CASE-4821"
    }


def test_expanded_cases_preserve_completion_nonoccurrence_and_policy_scope(
    service: ChatService,
) -> None:
    resolved = service.chat(
        "What was confirmed and completed to resolve CASE-4825?",
        DEMO_USERS["demo-agent-alex"],
    )
    reproduction = service.chat(
        "Does CASE-4823 not being reproduced prove the issue did not occur?",
        DEMO_USERS["demo-agent-jordan"],
    )
    standard_policy = service.chat(
        "What initial response target applies to CASE-4824?",
        DEMO_USERS["demo-agent-alex"],
    )

    assert "queued export replay completed" in resolved.reply
    assert "**Verified completion or resolution**" in resolved.reply
    assert "does not establish that the reported issue never occurred" in (
        reproduction.reply
    )
    assert "does not prove the issue did not occur" in reproduction.reply
    assert "eight business hours" in standard_policy.reply
    assert "Escalation review" not in standard_policy.reply


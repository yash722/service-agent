from datetime import date

import pytest

from servicing_agent.auth import DEMO_USERS
from servicing_agent.database import Database
from servicing_agent.service import ChatService


@pytest.fixture()
def service(tmp_path) -> ChatService:
    database = Database(tmp_path / "answers.db")
    database.initialize()
    return ChatService(database, as_of=date(2026, 11, 7))


def test_citations_are_returned_sources_and_appear_inline(
    service: ChatService,
) -> None:
    response = service.chat(
        "Why was CASE-4821 escalated?",
        DEMO_USERS["demo-agent-alex"],
    )

    assert response.evidence_status == "sufficient"
    assert response.citations
    assert all(
        citation.citation_label in response.reply
        for citation in response.citations
    )
    assert {citation.source_id for citation in response.citations} == {
        "CASE-NOTE-4821"
    }
    assert "definitive root cause was connector retries" not in response.reply


def test_insufficient_evidence_is_not_fabricated(service: ChatService) -> None:
    response = service.chat(
        "Is on-site hardware replacement included for CASE-4821?",
        DEMO_USERS["demo-agent-alex"],
    )

    assert response.evidence_status == "insufficient"
    assert response.citations == []
    assert "insufficient" in response.reply
    assert "will not infer" in response.reply


def test_unauthorized_case_returns_no_protected_evidence(
    service: ChatService,
) -> None:
    response = service.chat(
        "Why was CASE-4821 escalated?",
        DEMO_USERS["demo-agent-jordan"],
    )

    assert "not authorized" in response.reply
    assert response.citations == []
    assert response.evidence_status == "insufficient"
    assert all("retrieval.lexical" not in step for step in response.trace)


